'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const html = fs.readFileSync(path.resolve(__dirname,'..','orbit360-platform','index.html'),'utf8');
let checks=0;
const check=(value,label)=>{assert.ok(value,label);checks++;};
check(/function inboxSoundScope\(\)/.test(html),'Country-sound-scope owner exists');
check(/const key=inboxSoundScope\(\);if\(inboxChimeDecision\(inboxSound,key,rows\)\)/.test(html),'Only current country sound scope passed on authorized readback');
check(/function soundPreferenceKey\(\).*inboxScope\(\)/.test(html),'Mute persists by user tenant role independently of current country');
check(/document\.addEventListener\('orbit:pais', paintCountry\)/.test(html),'Canonical country source is Orbit.pais');
const soundStart=html.indexOf('function inboxSoundScope(');
const soundEnd=html.indexOf('function soundPreferenceKey(',soundStart);
check(soundStart>0&&soundEnd>soundStart,'Country-scope implementation extracted');
const env={pais:'GT'},inbox=()=> 'tenantA|uidA|asesor';
const soundScope=new Function('Orbit','inboxScope',html.slice(soundStart,soundEnd)+';return inboxSoundScope;')(env,inbox);
check(soundScope()==='tenantA|uidA|asesor|GT','GT isolated');
env.pais='CO';check(soundScope()==='tenantA|uidA|asesor|CO','CO isolated');
env.pais='TODOS';check(soundScope()==='tenantA|uidA|asesor|TODOS','Direccion TODOS isolated');
env.pais='gt';check(soundScope()==='tenantA|uidA|asesor|GT','Country normalized');
const decisionStart=html.indexOf('function inboxChimeDecision(');
const decisionEnd=html.indexOf('function shouldPlayInboxChime(',decisionStart);
check(decisionStart>0&&decisionEnd>decisionStart,'Pure inbox ID decision found');
const decide=new Function(html.slice(decisionStart,decisionEnd)+';return inboxChimeDecision;')();
const n=id=>({eventId:id,archived:false,globalResolved:false,read:false,acknowledged:false});
const st={scope:'',initialized:false,seen:new Set()};
env.pais='GT';
check(decide(st,soundScope(),[n('n1')])===false,'GT baseline silent');
check(decide(st,soundScope(),[n('n1'),n('n2')])===true,'New GT event audible once');
check(decide(st,soundScope(),[n('n2')])===false,'Repeat GT silent');
env.pais='CO';
check(decide(st,soundScope(),[n('n1'),n('n2'),n('n3')])===false,'Country GT to CO silent even if other country notices already existed');
check(decide(st,soundScope(),[n('n2'),n('n3')])===false,'CO repeats silent');
check(decide(st,soundScope(),[n('n2'),n('n3'),n('n4')])===true,'New CO event audible');
env.pais='TODOS';
check(decide(st,soundScope(),[n('n1'),n('n2'),n('n3'),n('n4')])===false,'Direccion TODAS baseline silent');
env.pais='GT';
check(decide(st,soundScope(),[n('n1'),n('n2')])===false,'Return to GT baseline silent');
console.log('I6_6_INBOX_CHIME_COUNTRY_SCOPE_SOURCE_PASS checks='+checks+' no_live_writes=true');
